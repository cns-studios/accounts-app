#!/usr/bin/env python3
"""Print measured token.json format facts and write docs/token_format.md."""

import json
from collections import Counter
from pathlib import Path

root = Path(__file__).resolve().parents[1]
data = json.loads((root / "tokens.json").read_text())
nodes = []
style_keys = Counter()
node_types = Counter()
units = Counter()


def value(v):
    return v.get("content") if isinstance(v, dict) else v


def walk(node):
    if not isinstance(node, dict) or node.get("type") != "element":
        return
    content = node["content"]
    nodes.append(content)
    node_types[content.get("elementType")] += 1
    for key, raw in content.get("style", {}).items():
        style_keys[key] += 1
        item = value(raw)
        if isinstance(item, str):
            if item.endswith("px"):
                units["px"] += 1
            elif item.startswith("rgba("):
                units["rgba"] += 1
            else:
                units["unitless/literal"] += 1
    for child in content.get("children", []):
        walk(child)


walk(data["componentUIDLs"][0]["node"])
root_node = nodes[0]
lines = [
    "# Token format",
    "",
    "Generated by `tools/token_format.py` from `tokens.json`; counts are measured, not inferred.",
    "",
    f"- Component: `{data['componentUIDLs'][0]['name']}`",
    f"- Element nodes: **{len(nodes)}**",
    f"- Root frame: width `{value(root_node['style']['width'])}`, height `{value(root_node['style']['height'])}`",
    "- Node structure: each element has `type=element`, `content.elementType`, `content.name`, `content.style`, optional `content.attrs`, and `content.children`; text leaves use `type=static` and `content`.",
    "- Layout: CSS/UIDL-like flex properties (`display`, direction, alignment, gap, padding, sizing) plus absolute `position`, `top`, and `left`.",
    "- Assets: image nodes store data URIs in `content.attrs.src` and alt text in `content.attrs.alt`.",
    "- Colors: `rgba(r, g, b, alpha)` strings in style values.",
    "- Typography: font family, size, weight/style, alignment, line-height, and decoration are in text-node style values.",
    "- Gradients: none present in the exported node styles.",
    "- Shadows: none present in the exported node styles.",
    "",
    "## Measured node types",
    "",
    "| Node type | Count |",
    "|---|---:|",
]
lines += [f"| `{key}` | {node_types[key]} |" for key in sorted(node_types)]
lines += ["", "## Measured style keys", "", "| Style key | Count |", "|---|---:|"]
lines += [f"| `{key}` | {style_keys[key]} |" for key in sorted(style_keys)]
lines += ["", "## Measured value units", "", "| Unit category | Count |", "|---|---:|"]
lines += [f"| `{key}` | {units[key]} |" for key in sorted(units)]
(root / "docs/token_format.md").write_text("\n".join(lines) + "\n")
print(f"total nodes: {len(nodes)}")
print("node types:", dict(node_types))
print("style keys:", sorted(style_keys))
print("units:", dict(units))
